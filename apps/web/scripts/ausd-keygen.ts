// Generates fresh TESTNET-ONLY keys for the AUSD lane and writes them to <repo root>/.env.ausd (mode 600, gitignored).
// Prints PUBLIC addresses only. Refuses to overwrite an existing file.
//   pnpm --filter web exec tsx scripts/ausd-keygen.ts
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";

const out = resolve(__dirname, "../../../.env.ausd");
if (existsSync(out)) {
  console.error(`${out} already exists; not overwriting it.`);
  process.exit(1);
}

const relayer = generatePrivateKey();
const treasury = generatePrivateKey();
const agent = generatePrivateKey();
const addr = (k: `0x${string}`) => privateKeyToAccount(k).address;

const body = `# AUSD lane, Base Sepolia (chainId 84532). TESTNET ONLY: never fund these with real assets. Generated by apps/web/scripts/ausd-keygen.ts.
# Never commit this file (.gitignore covers .env.*). Copy the lines you need into .env.
BASE_SEPOLIA_RPC_URL=https://sepolia.base.org
AUSD_TOKEN_ADDRESS=0xa9012a055bd4e0eDfF8Ce09f960291C09D5322dC
AUSD_DECIMALS=6
# Rove's AUSD receive address (public). Its key below is not read by any app; keep it to move the float later.
AUSD_PAY_TO=${addr(treasury)}
AUSD_TREASURY_PRIVATE_KEY=${treasury}
# Relayer: submits transferWithAuthorization and pays the gas. Worker only, never on Vercel. Address: ${addr(relayer)}
AUSD_RELAYER_PRIVATE_KEY=${relayer}
# Demo "AI agent" wallet for scripts/x402-agent-pay.ts (holds AUSD, no ETH needed). Address: ${addr(agent)}
X402_AGENT_PRIVATE_KEY=${agent}
`;
writeFileSync(out, body, { mode: 0o600 });
console.log(`wrote ${out} (mode 600)`);
console.log("AUSD_PAY_TO (treasury)", addr(treasury));
console.log("relayer               ", addr(relayer));
console.log("x402 agent            ", addr(agent));
