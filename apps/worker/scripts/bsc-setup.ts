const [cmd = "init", ...args] = process.argv.slice(2);
const commands: Record<string, () => Promise<unknown>> = {
  init,
  status: () => status(args),
  address: () => address(args[0]),
  compile: () => compile(args.includes("--write")),
  simulate,
  deploy,
  mint: () => mint(args[0], args[1]),
  "send-gas": () => sendGas(args[0], args[1]),
  pay: () => pay(args[0], args[1]),
  replay: () => replay(args[0], args[1]),
  "live-demo": () => liveDemo(args[0]),
};

const run = commands[cmd];
if (!run) {
  console.error(`unknown command ${cmd}. Commands: ${Object.keys(commands).join(", ")}`);
  process.exit(2);
}
run()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error(`bsc-setup ${cmd} failed: ${err instanceof Error ? err.message : String(err)}`);
    process.exit(1);
  });
