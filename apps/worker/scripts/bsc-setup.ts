async function demoPayment(deps: Awaited<ReturnType<typeof demoDeps>>, address: Address, usd: string, expiresAt: Date, index: number) {
  const local = fromMinor((toUnits(usd, 2) * 12_900n) / 10_000n, "SGD"); // the demo merchant's S$ at 1.2900, bigint math
  const quote: Quote = { local, usd: money(usd, "USD"), rate: "1.2900", sendMaxUsd: usd, expiresAt: expiresAt.toISOString() };
  return deps.db.insertPayment({
    id: `${newId("pay")}_bsc${index}`,
    merchantId: "ahseng",
    source: "fixed_qr",
    invoiceId: null,
    lines: [],
    local,
    quote,
    charge: quote.usd,
    method: "bnb",
    payer: null,
    bnbDepositAddress: address,
  });
}

async function watchUntilSettled(
  deps: Awaited<ReturnType<typeof demoDeps>>,
  rpcUrl: string,
  token: Address,
  decimals: number,
  symbol: string,
  fromBlock: bigint,
  paymentId: string,
): Promise<DepositOutcome[]> {
  const source = createRpcSource({ rpcUrl, token, maxBlockRange: 5_000n });
  const head = await source.head();
  const watcher = createBnbWatcher(deps, source, {
    decimals,
    symbol,
    confirmations: BNB_CONFIRMATIONS,
    rescanBlocks: head - fromBlock + 1n,
    lateGraceMs: LATE_GRACE_MS,
    settle: "now",
  });
  const outcomes: DepositOutcome[] = [];
  for (let i = 0; i < 60; i++) {
    const r = await watcher.poll();
    outcomes.push(...r.outcomes.filter((o) => o.kind !== "ignored"));
    if (outcomes.some((o) => "paymentId" in o && o.paymentId === paymentId)) break;
    await new Promise((r) => setTimeout(r, 1000));
  }
  for (let i = 0; i < 50; i++) {
    const p = await deps.db.getPayment(paymentId);
    if (p && p.status !== "authorized" && p.status !== "settling") break;
    await new Promise((r) => setTimeout(r, 200));
  }
  const p = await deps.db.getPayment(paymentId);
  const bal = await deps.db.getBalance("ahseng");
  console.log(`\nResult: payment ${paymentId} is ${p?.status} (method ${p?.method}); merchant ledger available ${bal.available.amount} SGD`);
  return outcomes;
}

async function replay(txHash: string | undefined, tokenArg: string | undefined): Promise<void> {
  if (!txHash || !/^0x[0-9a-fA-F]{64}$/.test(txHash)) throw new Error("replay <txHash> [token]: a 0x… transaction hash of an ERC-20 transfer on BSC testnet");
  const env = readEnvFile();
  const { pub, rpcUrl } = clients(env);
  await checkChain(pub);
  const only = tokenArg ? parseAddress(tokenArg, "replay [token]").toLowerCase() : null;
  const receipt = await pub.getTransactionReceipt({ hash: txHash as Hex });
  const raw = receipt.logs.find(
    (l) => l.topics[0] === keccak256(toHex("Transfer(address,address,uint256)")) && l.topics.length === 3 && (!only || l.address.toLowerCase() === only),
  );
  if (!raw) throw new Error(`that transaction has no ERC-20 Transfer log${only ? ` from ${tokenArg}` : ""}`);
  const ev = decodeEventLog({ abi: [TRANSFER_EVENT], data: raw.data, topics: raw.topics });
  const token = getAddress(raw.address);
  const facts = await tokenFacts(pub, token);
  const block = await pub.getBlock({ blockNumber: receipt.blockNumber });
  const paidAt = new Date(Number(block.timestamp) * 1000);
  // charge = the transferred value floored to cents (so the real transfer pays it in full)
  const cents = ev.args.value / 10n ** BigInt(facts.decimals - 2);
  if (cents <= 0n) throw new Error("that transfer is under 0.01 tokens; pick a bigger one");
  const usd = fromUnits(cents, 2);
  console.log(`Replaying ${txHash}\n  ${facts.symbol} (${token}, ${facts.decimals} decimals): ${formatUnits(ev.args.value, facts.decimals)} → ${ev.args.to} in block ${receipt.blockNumber} at ${paidAt.toISOString()}`);
  const deps = await demoDeps();
  const payment = await demoPayment(deps, ev.args.to, usd, new Date(paidAt.getTime() + 60_000), 0);
  console.log(`  bnb payment ${payment.id}: charge US$${usd}, deposit address ${ev.args.to} (payment created before the transfer, quote valid at its block)`);
  const outcomes = await watchUntilSettled(deps, rpcUrl, token, facts.decimals, facts.symbol, receipt.blockNumber, payment.id);
  console.log("Outcomes:", outcomes);
  await deps.db.close();
}

async function liveDemo(amountArg: string | undefined): Promise<void> {
  const env = readEnvFile();
  const { pub, rpcUrl } = clients(env);
  await checkChain(pub);
  const token = tokenOf(env);
  const facts = await tokenFacts(pub, token);
  const amount = parseAmount(amountArg ?? "9.69", "live-demo [amount]");
  const { deployer } = clients(env);
  if (!deployer) throw new Error("BSC_DEPLOYER_KEY missing: run init");
  const held = await pub.readContract({ address: token, abi: TUSDT_ABI, functionName: "balanceOf", args: [deployer.address] });
  if (held < parseUnits(amount, facts.decimals)) {
    console.log(`Deployer holds ${formatUnits(held, facts.decimals)} ${facts.symbol}; minting ${amount} to it first (stand-in customer)`);
    await mint(deployer.address, amount);
  }
  const keys = depositKeyring(need(env, "BSC_DEPOSIT_MNEMONIC"));
  // a fresh index well away from the DB sequence's range, so the demo never reuses a real payment's address
  const index = 1_000_000 + Math.floor(Math.random() * 1_000_000);
  const address = keys.address(index);
  const deps = await demoDeps();
  const payment = await demoPayment(deps, address, amount, new Date(Date.now() + 10 * 60_000), index);
  console.log(`bnb payment ${payment.id}: charge US$${amount}, deposit address m/44'/60'/0'/0/${index} = ${address}`);
  const from = await pub.getBlockNumber();
  const hash = await pay(address, amount);
  const outcomes = await watchUntilSettled(deps, rpcUrl, token, facts.decimals, facts.symbol, from, payment.id);
  console.log("Outcomes:", outcomes, `\nPay-in tx: ${EXPLORER}/tx/${hash}`);
  await deps.db.close();
}

