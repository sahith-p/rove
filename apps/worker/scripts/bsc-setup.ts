async function init(): Promise<void> {
  const env = readEnvFile();
  const created: Record<string, string> = {};
  if (!env.get("BSC_DEPOSIT_MNEMONIC")) {
    const mnemonic = generateMnemonic(english);
    created.BSC_DEPOSIT_MNEMONIC = mnemonic;
    created.BSC_DEPOSIT_XPUB = depositKeyring(mnemonic).xpub;
  } else if (!env.get("BSC_DEPOSIT_XPUB")) {
    created.BSC_DEPOSIT_XPUB = depositKeyring(env.get("BSC_DEPOSIT_MNEMONIC")!).xpub;
  }
  if (!env.get("BSC_DEPLOYER_KEY")) {
    const key = generatePrivateKey();
    created.BSC_DEPLOYER_KEY = key;
    created.BSC_DEPLOYER_ADDRESS = privateKeyToAccount(key).address;
  }
  if (!env.get("BSC_RPC_URL")) created.BSC_RPC_URL = DEFAULT_BSC_RPC_URL;
  if (!env.get("BSC_TOKEN_DECIMALS")) created.BSC_TOKEN_DECIMALS = "18";
  if (Object.keys(created).length) {
    writeEnvFile(created);
    console.log(`Wrote ${Object.keys(created).join(", ")} to ${ENV_PATH} (mode 600). Secrets are not printed.`);
  } else {
    console.log(`${ENV_PATH} already has the keys; nothing generated.`);
  }
  chmodSync(ENV_PATH, 0o600);
  await status([]);
}

