/** Sets keys in .env.bsc, keeping everything else; file mode 600. */
function writeEnvFile(updates: Record<string, string>): void {
  const lines = existsSync(ENV_PATH) ? readFileSync(ENV_PATH, "utf8").replace(/\n+$/, "").split("\n") : [...HEADER];
  for (const [key, value] of Object.entries(updates)) {
    const line = `${key}=${/\s/.test(value) ? `"${value}"` : value}`;
    const i = lines.findIndex((l) => new RegExp(`^\\s*${key}\\s*=`).test(l));
    if (i >= 0) lines[i] = line;
    else lines.push(line);
  }
  writeFileSync(ENV_PATH, lines.join("\n") + "\n", { mode: 0o600 });
  chmodSync(ENV_PATH, 0o600);
}

function need(env: EnvFile, key: string): string {
  const v = env.get(key) || process.env[key];
  if (!v) throw new Error(`${key} is missing: run \`bsc-setup.ts init\` first (or set it in .env.bsc)`);
  return v;
}

// ------------------------------------------------------------------ chain

function clients(env: EnvFile) {
  const rpcUrl = env.get("BSC_RPC_URL") || DEFAULT_BSC_RPC_URL;
  const transport = http(rpcUrl, { timeout: 20_000, retryCount: 2 });
  const pub = createPublicClient({ chain: bscTestnet, transport });
  const key = env.get("BSC_DEPLOYER_KEY") as Hex | undefined;
  const deployer = key ? privateKeyToAccount(key) : null;
  const wallet = deployer ? createWalletClient({ chain: bscTestnet, transport, account: deployer }) : null;
  return { rpcUrl, pub, deployer, wallet };
}

async function checkChain(pub: ReturnType<typeof clients>["pub"]): Promise<void> {
  const id = await pub.getChainId();
  if (id !== BSC_TESTNET_CHAIN_ID) throw new Error(`RPC is chain ${id}, not BSC testnet (${BSC_TESTNET_CHAIN_ID}). Refusing.`);
}

function tokenOf(env: EnvFile): Address {
  const t = env.get("BSC_TOKEN_ADDRESS") || process.env.BSC_TOKEN_ADDRESS;
  if (!t) throw new Error("BSC_TOKEN_ADDRESS is missing: run `bsc-setup.ts deploy` (needs tBNB on the deployer), or set it in .env.bsc");
  if (!isAddress(t, { strict: false })) throw new Error("BSC_TOKEN_ADDRESS is not an address");
  return getAddress(t);
}

async function tokenFacts(pub: ReturnType<typeof clients>["pub"], token: Address) {
  const read = <F extends "name" | "symbol" | "decimals" | "totalSupply">(functionName: F) =>
    pub.readContract({ address: token, abi: TUSDT_ABI, functionName }) as Promise<F extends "decimals" ? number : F extends "totalSupply" ? bigint : string>;
  const [name, symbol, decimals, totalSupply] = await Promise.all([read("name"), read("symbol"), read("decimals"), read("totalSupply")]);
  return { name, symbol, decimals, totalSupply };
}

async function waitReceipt(pub: ReturnType<typeof clients>["pub"], hash: Hex, what: string) {
  console.log(`  ${what}: ${hash}\n  ${EXPLORER}/tx/${hash}`);
  const receipt = await pub.waitForTransactionReceipt({ hash, timeout: 120_000 });
  if (receipt.status !== "success") throw new Error(`${what} reverted (${hash})`);
  console.log(`  confirmed in block ${receipt.blockNumber}`);
  return receipt;
}

function parseAddress(v: string | undefined, what: string): Address {
  if (!v || !isAddress(v, { strict: false })) throw new Error(`${what}: expected an 0x address, got ${v ?? "nothing"}`);
  return getAddress(v);
}

function parseAmount(v: string | undefined, what: string): string {
  if (!v || !/^\d+(\.\d+)?$/.test(v)) throw new Error(`${what}: expected a decimal amount like 9.69, got ${v ?? "nothing"}`);
  return v;
}

