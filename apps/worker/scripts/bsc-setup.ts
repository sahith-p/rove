function solcCompile(source: string): { bytecode: Hex; abi: unknown[] } {
  const res = spawnSync("npx", ["--yes", `solc@${TUSDT_SOLC.version}`, "--standard-json"], {
    input: JSON.stringify(solcInput(source)),
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (res.status !== 0) throw new Error(`solc failed: ${res.stderr || res.error}`);
  const json = res.stdout.slice(res.stdout.indexOf("{"));
  const out = JSON.parse(json) as {
    errors?: { severity: string; formattedMessage: string }[];
    contracts?: Record<string, Record<string, { abi: unknown[]; evm: { bytecode: { object: string } } }>>;
  };
  const errors = (out.errors ?? []).filter((e) => e.severity === "error");
  if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join("\n"));
  for (const w of out.errors ?? []) console.log(w.formattedMessage);
  const c = out.contracts?.[TUSDT_SOURCE_FILE]?.[TUSDT_CONTRACT];
  if (!c) throw new Error("solc output has no TestUSDT contract");
  return { bytecode: `0x${c.evm.bytecode.object}`, abi: c.abi };
}

async function compile(write: boolean): Promise<void> {
  const source = readFileSync(SOL_PATH, "utf8");
  const sha = createHash("sha256").update(source).digest("hex");
  console.log(`Compiling ${SOL_PATH} with solc-js ${TUSDT_SOLC.version} (optimizer ${TUSDT_SOLC.settings.optimizer.runs} runs, evm ${TUSDT_SOLC.settings.evmVersion})`);
  const { bytecode, abi } = solcCompile(source);
  const want = new Set(TUSDT_ABI.filter((x) => x.type === "function" || x.type === "event").map((x) => `${x.type}:${"name" in x ? x.name : ""}`));
  const got = new Set((abi as { type: string; name?: string }[]).filter((x) => x.type === "function" || x.type === "event").map((x) => `${x.type}:${x.name ?? ""}`));
  const missing = [...want].filter((x) => !got.has(x));
  const extraAbi = [...got].filter((x) => !want.has(x));
  if (missing.length || extraAbi.length) throw new Error(`TUSDT_ABI out of date: missing ${missing.join(", ") || "-"}; extra ${extraAbi.join(", ") || "-"}`);
  console.log(`  source sha256 ${sha}${sha === TUSDT_SOURCE_SHA256 ? " (matches tusdt.ts)" : " (tusdt.ts has a different hash)"}`);
  console.log(`  bytecode ${(bytecode.length - 2) / 2} bytes, keccak ${keccak256(bytecode)}${bytecode === TUSDT_BYTECODE ? " (matches tusdt.ts)" : " (DIFFERS from tusdt.ts)"}`);
  if (write) {
    let ts = readFileSync(TUSDT_TS_PATH, "utf8");
    ts = ts.replace(/export const TUSDT_SOURCE_SHA256 = "[^"]*";/, `export const TUSDT_SOURCE_SHA256 = "${sha}";`);
    ts = ts.replace(/export const TUSDT_BYTECODE: Hex = "[^"]*";/, `export const TUSDT_BYTECODE: Hex =\n  "${bytecode}";`);
    ts = ts.replace(/export const TUSDT_BYTECODE: Hex =\n  "[^"]*";/, `export const TUSDT_BYTECODE: Hex =\n  "${bytecode}";`);
    writeFileSync(TUSDT_TS_PATH, ts);
    console.log(`  wrote ${TUSDT_TS_PATH}`);
  } else if (bytecode !== TUSDT_BYTECODE || sha !== TUSDT_SOURCE_SHA256) {
    throw new Error("committed bytecode is stale: run `bsc-setup.ts compile --write`");
  }
}

async function simulate(): Promise<void> {
  const env = readEnvFile();
  const { pub, rpcUrl } = clients(env);
  await checkChain(pub);
  const deployer = clients(env).deployer?.address ?? privateKeyToAccount(generatePrivateKey()).address;
  console.log(`Simulating tUSDT on BSC testnet via ${rpcUrl} as ${deployer} (no transaction is sent)`);

  const gas = await pub.estimateGas({ account: deployer, data: TUSDT_BYTECODE });
  const gasPrice = await pub.getGasPrice();
  console.log(`  deploy: ${gas} gas × ${formatUnits(gasPrice, 9)} gwei = ${formatEther(gas * gasPrice)} tBNB`);
  const { data: runtime } = await pub.call({ account: deployer, data: TUSDT_BYTECODE });
  if (!runtime || runtime === "0x") throw new Error("deploy simulation returned no code");
  console.log(`  runtime code: ${(runtime.length - 2) / 2} bytes`);

  const at: Address = "0x00000000000000000000000000000000000ce0de";
  const read = async (functionName: "name" | "symbol" | "decimals" | "owner" | "totalSupply") => {
    const { data } = await pub.call({ to: at, data: encodeFunctionData({ abi: TUSDT_ABI, functionName }), stateOverride: [{ address: at, code: runtime }] });
    return decodeFunctionResult({ abi: TUSDT_ABI, functionName, data: data! });
  };
  console.log(`  name ${await read("name")} · symbol ${await read("symbol")} · decimals ${await read("decimals")} · owner ${await read("owner")}`);

  const customer: Address = "0x90F79bf6EB2c4f870365E785982E1f101E93b906";
  const deposit: Address = "0x70997970C51812dc3A010C7d01b50e0d17dc79C8";
  const amount = parseUnits("9.69", 18);
  const mintOk = await pub.call({ account: deployer, to: at, data: encodeFunctionData({ abi: TUSDT_ABI, functionName: "mint", args: [customer, amount] }), stateOverride: [{ address: at, code: runtime }] });
  console.log(`  mint by the deployer: ok (${mintOk.data ?? "0x"})`);
  try {
    await pub.call({ account: customer, to: at, data: encodeFunctionData({ abi: TUSDT_ABI, functionName: "mint", args: [customer, amount] }), stateOverride: [{ address: at, code: runtime }] });
    throw new Error("mint by a non-owner did not revert");
  } catch (err) {
    if (err instanceof Error && /did not revert/.test(err.message)) throw err;
    console.log("  mint by anyone else: reverts (only the deployer mints)");
  }
  // balanceOf is mapping slot 1 (owner is immutable, totalSupply is slot 0): give the customer a balance, then transfer
  const slot = keccak256(encodeAbiParameters([{ type: "address" }, { type: "uint256" }], [customer, 1n]));
  const override = [{ address: at, code: runtime, stateDiff: [{ slot, value: toHex(amount, { size: 32 }) }] }];
  const transfer = encodeFunctionData({ abi: TUSDT_ABI, functionName: "transfer", args: [deposit, amount] });
  const { data: ok } = await pub.call({ account: customer, to: at, data: transfer, stateOverride: override });
  console.log(`  customer transfer(${deposit}, 9.69 tUSDT): returns ${decodeFunctionResult({ abi: TUSDT_ABI, functionName: "transfer", data: ok! })}`);
  try {
    const sim = await pub.simulateBlocks({ blocks: [{ stateOverrides: override, calls: [{ account: customer, to: at, data: transfer }] }] });
    const logs = sim[0]?.calls[0]?.logs ?? [];
    for (const l of logs) {
      const ev = decodeEventLog({ abi: [TRANSFER_EVENT], data: l.data, topics: l.topics });
      console.log(`  eth_simulateV1 → ${ev.eventName}(${ev.args.from} → ${ev.args.to}, ${formatUnits(ev.args.value, 18)})`);
    }
  } catch (err) {
    console.log(`  (eth_simulateV1 not available on this RPC: ${err instanceof Error ? err.message.split("\n")[0] : err})`);
  }
}

async function deploy(): Promise<void> {
  const env = readEnvFile();
  const { pub, wallet, deployer } = clients(env);
  if (!wallet || !deployer) throw new Error("BSC_DEPLOYER_KEY missing: run init");
  await checkChain(pub);
  if (env.get("BSC_TOKEN_ADDRESS")) console.log(`(replacing BSC_TOKEN_ADDRESS=${env.get("BSC_TOKEN_ADDRESS")})`);
  const balance = await pub.getBalance({ address: deployer.address });
  if (balance === 0n) throw new Error(`deployer ${deployer.address} has no tBNB: fund it from a faucet first`);
  const hash = await wallet.deployContract({ abi: TUSDT_ABI, bytecode: TUSDT_BYTECODE });
  const receipt = await waitReceipt(pub, hash, "deploy tUSDT");
  const token = receipt.contractAddress;
  if (!token) throw new Error("no contract address in the receipt");
  const facts = await tokenFacts(pub, token);
  if (facts.decimals !== 18 || facts.symbol !== "tUSDT") throw new Error(`unexpected token facts: ${JSON.stringify(facts)}`);
  writeEnvFile({ BSC_TOKEN_ADDRESS: token, BSC_TOKEN_DECIMALS: String(facts.decimals) });
  console.log(`tUSDT deployed at ${token} (${facts.name}, ${facts.decimals} decimals) → ${EXPLORER}/address/${token}\nWrote BSC_TOKEN_ADDRESS to .env.bsc.`);
}

async function mint(to: string | undefined, amount: string | undefined): Promise<void> {
  const env = readEnvFile();
  const { pub, wallet } = clients(env);
  if (!wallet) throw new Error("BSC_DEPLOYER_KEY missing: run init");
  await checkChain(pub);
  const token = tokenOf(env);
  const dest = parseAddress(to, "mint <to>");
  const value = parseUnits(parseAmount(amount, "mint <amount>"), 18);
  const hash = await wallet.writeContract({ address: token, abi: TUSDT_ABI, functionName: "mint", args: [dest, value] });
  await waitReceipt(pub, hash, `mint ${amount} tUSDT → ${dest}`);
}

async function sendGas(to: string | undefined, amount: string | undefined): Promise<void> {
  const env = readEnvFile();
  const { pub, wallet } = clients(env);
  if (!wallet) throw new Error("BSC_DEPLOYER_KEY missing: run init");
  await checkChain(pub);
  const dest = parseAddress(to, "send-gas <to>");
  const hash = await wallet.sendTransaction({ to: dest, value: parseEther(parseAmount(amount, "send-gas <tBNB>")) });
  await waitReceipt(pub, hash, `send ${amount} tBNB → ${dest}`);
}

async function pay(to: string | undefined, amount: string | undefined): Promise<Hex> {
  const env = readEnvFile();
  const { pub, wallet } = clients(env);
  if (!wallet) throw new Error("BSC_DEPLOYER_KEY missing: run init");
  await checkChain(pub);
  const token = tokenOf(env);
  const decimals = Number(env.get("BSC_TOKEN_DECIMALS") || "18");
  const dest = parseAddress(to, "pay <address>");
  // exactly what the pay page's wallet button sends: token.transfer(depositAddress, parseUnits(amount, decimals))
  const hash = await wallet.writeContract({ address: token, abi: TUSDT_ABI, functionName: "transfer", args: [dest, parseUnits(parseAmount(amount, "pay <amount>"), decimals)] });
  await waitReceipt(pub, hash, `transfer ${amount} → ${dest}`);
  return hash;
}

